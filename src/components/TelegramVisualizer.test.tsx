import React from 'react';
import { strict as assert } from 'node:assert';
import { test } from 'node:test';
import { create, act } from 'react-test-renderer';
import { TelegramVisualizer, buildStandardGroupTelegram } from './TelegramVisualizer';
import { APCICode, type TelegramParams } from '../types';
import { telegramTiming, accessWaitBits } from '../knx/tp1Timing';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const base:TelegramParams={repeatFlag:'1',targetType:'1',command:APCICode.GroupValueWrite,source:{area:1,line:1,device:10},destination:{main:1,middle:0,sub:1},routingCounter:6,priority:'11',dptType:'1.001',ackType:'CC'};
const text=(node:any):string=>typeof node==='string'?node:Array.isArray(node)?node.map(text).join(''):node?.children?text(node.children):'';
const generate=(r:any)=>r.root.findAllByType('button').find((b:any)=>text(b)==='Generate Telegram').props.onClick();
test('Off survives Write → Read → Write and generated bytes match the editor',async()=>{
 let r:any;await act(()=>{r=create(<TelegramVisualizer/>);});
 const change=async(label:string,value:string)=>act(()=>r.root.findByProps({'aria-label':label}).props.onChange({target:{value}}));
 await change('Switch value','0');await change('APCI group-value service','0000');await change('APCI group-value service','0010');
 assert.equal(r.root.findByProps({'aria-label':'Switch value'}).props.value,'0');
 await act(()=>generate(r));assert.match(text(r.toJSON()),/Hex Dump: BC 11 0A 08 01 E1 00 80 30/);
 await change('Switch value','1');await act(()=>generate(r));assert.match(text(r.toJSON()),/Hex Dump: BC 11 0A 08 01 E1 00 81 31/);
 await act(()=>r.unmount());
});
test('Semantic value and invalid input survive a hidden editor; address edits clear presets',async()=>{
 let r:any;await act(()=>{r=create(<TelegramVisualizer/>);});
 const change=async(label:string,value:string)=>act(()=>r.root.findByProps({'aria-label':label}).props.onChange({target:{value}}));
 await change('Datapoint type','9.001');await change('Temperature (°C)','-30');
 await change('APCI group-value service','0000');await change('APCI group-value service','0001');
 assert.equal(r.root.findByProps({'aria-label':'Temperature (°C)'}).props.value,'-30');
 await act(()=>generate(r));assert.match(text(r.toJSON()),/00 40 8A 24/);
 await change('Temperature (°C)','');await change('APCI group-value service','0000');await change('APCI group-value service','0010');
 assert.equal(r.root.findByProps({'aria-label':'Temperature (°C)'}).props.value,'');
 await act(()=>generate(r));assert.match(text(r.toJSON()),/Correct the invalid DPT value/);
 const preset=()=>r.root.findAllByType('button').find((b:any)=>text(b).includes('Switch Light On'));
 await act(()=>preset().props.onClick());assert.equal(preset().props['aria-pressed'],true);
 await change('Source area','16');assert.equal(preset().props['aria-pressed'],false);
 assert.equal(r.root.findByProps({'aria-label':'Source area'}).props.value,16);
 assert.match(text(r.toJSON()),/Source area: enter a whole number from 0 to 15/);
 await change('Source area','1.5');assert.equal(r.root.findByProps({'aria-label':'Source area'}).props.value,1.5);
 await act(()=>generate(r));assert.doesNotMatch(text(r.toJSON()),/Hex Dump:/);
 await change('Source area','');assert.equal(r.root.findByProps({'aria-label':'Source area'}).props.value,'');
 await act(()=>r.unmount());
});
test('All next-access priority/repeat combinations and exact nominal boundaries',()=>{
 for(const priority of ['00','10','01','11'] as const)for(const repeatFlag of ['0','1'] as const){
  const expected=repeatFlag==='0'||priority==='00'||priority==='10'?50:53;
  assert.equal(accessWaitBits({priority,repeatFlag}),expected);
  const t=telegramTiming(9,{priority,repeatFlag});
  assert.equal(t.frameBits,115);assert.equal(t.exchangeBits,141);assert.equal(t.idleBits,expected);
  assert.ok(Math.abs(t.exchangeMs-14.6875)<1e-10);
  assert.ok(Math.abs(t.earliestNextMs-(141+expected)/9.6)<1e-10);
 }
 assert.equal(telegramTiming(23).frameBits,297);
});
test('Next-access controls change timing immediately without changing bytes or dirty state',async()=>{
 let r:any;await act(()=>{r=create(<TelegramVisualizer/>);});await act(()=>generate(r));
 const dump=()=>text(r.toJSON()).match(/Hex Dump: ([A-F0-9 ]+)/)?.[1];const before=dump();
 await act(()=>r.root.findByProps({'aria-label':'Next telegram priority'}).props.onChange({target:{value:'10'}}));
 assert.equal(dump(),before);assert.match(text(r.toJSON()),/19.896 ms from frame start/);assert.match(text(r.toJSON()),/Generated telegram matches/);
 await act(()=>r.root.findByProps({'aria-label':'Demonstration response'}).props.onChange({target:{value:'NONE'}}));
 assert.doesNotMatch(text(r.toJSON()),/19.896 ms from frame start/);assert.match(text(r.toJSON()),/Silent observation slot/);
 await act(()=>r.unmount());
});
test('Frame vectors, check byte, physical parity and invalid address boundaries',()=>{
 const built=buildStandardGroupTelegram(base,'1');assert.equal(built.stream.length,115);
 assert.equal(built.cards.reduce((n,b)=>n^parseInt(b.hex,16),0),255);
 for(const b of built.cards){assert.equal((b.physicalBits.dataReversed+b.physicalBits.parity).replace(/0/g,'').length%2,0);assert.equal(b.physicalBits.dataReversed,b.logicalBinary.split('').reverse().join(''));}
 for(const area of [-1,16,1.5,NaN])assert.throws(()=>buildStandardGroupTelegram({...base,source:{...base.source,area}},'1'));
 assert.throws(()=>buildStandardGroupTelegram({...base,destination:{main:0,middle:0,sub:0}},'1'));
 assert.equal(buildStandardGroupTelegram({...base,command:APCICode.GroupValueRead},'').cards.map(b=>b.hex).join(' '),'BC 11 0A 08 01 E1 00 00 B0');
});
